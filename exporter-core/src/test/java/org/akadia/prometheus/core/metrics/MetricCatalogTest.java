package org.akadia.prometheus.core.metrics;

import org.akadia.prometheus.core.config.MetricId;
import org.akadia.prometheus.core.support.ExporterHarness;
import org.akadia.prometheus.core.support.FakeBackendServer;
import org.akadia.prometheus.core.support.FakeProxyPlatform;
import org.akadia.prometheus.core.support.ScrapedMetrics;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.EnumSet;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.TreeSet;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Generates the metric reference from the running exporter and checks it against the
 * committed documentation.
 *
 * <p>Hand-maintained metric tables rot: a metric gets renamed, a label is added, and the
 * README keeps describing last year's output. Here the documentation is derived from an
 * actual scrape with every metric group enabled, so a change to the code either updates
 * the docs or fails the build.
 *
 * <p>Regenerate after an intentional change:
 * <pre>mvn -pl exporter-core test -Dtest=MetricCatalogTest -Dmetrics.catalog.write=true</pre>
 */
class MetricCatalogTest {

    private static final Path CATALOG = Path.of("..", "docs", "METRICS.md");
    private static final String WRITE_PROPERTY = "metrics.catalog.write";

    @Test
    @DisplayName("docs/METRICS.md matches what the exporter actually emits")
    void catalogMatchesReality() throws IOException {
        String generated = generateCatalog();

        if (Boolean.getBoolean(WRITE_PROPERTY)) {
            Files.createDirectories(CATALOG.getParent());
            Files.writeString(CATALOG, generated, StandardCharsets.UTF_8);
            return;
        }

        assertThat(CATALOG)
                .as("run with -D%s=true to regenerate", WRITE_PROPERTY)
                .exists();
        assertThat(normalise(Files.readString(CATALOG, StandardCharsets.UTF_8)))
                .as("docs/METRICS.md is out of date; regenerate with -D%s=true", WRITE_PROPERTY)
                .isEqualTo(normalise(generated));
    }

    private static String normalise(String text) {
        return text.replace("\r\n", "\n").strip();
    }

    private String generateCatalog() {
        FakeProxyPlatform platform = new FakeProxyPlatform()
                .addServer(FakeBackendServer.named("lobby"))
                .addPlayer("ExamplePlayer", "lobby", 42)
                .addPlugin("proxy-prometheus-exporter", "4.0.0");

        // A stub coordinator so the RedisBungee metrics appear in the reference too.
        org.akadia.prometheus.core.platform.NetworkStatsProvider networkStats =
                new org.akadia.prometheus.core.platform.NetworkStatsProvider() {
                    @Override
                    public int networkPlayerCount() {
                        return 0;
                    }

                    @Override
                    public int proxyCount() {
                        return 0;
                    }
                };

        try (ExporterHarness harness = ExporterHarness.start(platform, builder -> builder
                .enabledMetrics(EnumSet.allOf(MetricId.class))
                .namespace("minecraft_proxy"), networkStats, java.time.Clock.systemUTC())) {

            EventMetrics events = harness.exporter().events();
            events.recordConnection();
            events.recordLogin(true);
            events.recordDisconnect();
            events.recordChat();
            events.recordCommand("/tp");
            events.recordKick("lobby");
            events.recordServerSwitch("lobby", "survival");
            events.recordListPing();
            harness.exporter().runSamplersNow();

            ScrapedMetrics scrape = harness.scrape();

            StringBuilder out = new StringBuilder();
            out.append("# Metric reference\n\n");
            out.append("<!--\n");
            out.append("  Generated by MetricCatalogTest from a live scrape with every metric\n");
            out.append("  group enabled. Do not edit by hand; regenerate with\n");
            out.append("    mvn -pl exporter-core test -Dtest=MetricCatalogTest ")
                    .append("-D").append(WRITE_PROPERTY).append("=true\n");
            out.append("-->\n\n");
            out.append("`minecraft_proxy` is the default namespace; change it with the ");
            out.append("`namespace` setting.\n");
            out.append("Standard `jvm_*` and `process_*` metrics come from the Prometheus JVM ");
            out.append("instrumentation\nand are deliberately not namespaced, so ordinary JVM ");
            out.append("dashboards work unchanged.\n\n");
            out.append("| Metric | Type | Labels | Description |\n");
            out.append("| --- | --- | --- | --- |\n");

            Map<String, String> labelsByFamily = labelsByFamily(scrape);
            Map<String, String> sorted = new TreeMap<>();
            for (String family : scrape.familyNames()) {
                if (family.startsWith("jvm_") || family.startsWith("process_")) {
                    continue;
                }
                String type = scrape.typeOf(family).orElse("gauge");
                String labels = labelsByFamily.getOrDefault(family, "");
                String help = scrape.helpOf(family).orElse("");
                sorted.put(family, "| `" + family + "` | " + type + " | "
                        + (labels.isEmpty() ? "-" : labels) + " | " + help + " |\n");
            }
            sorted.values().forEach(out::append);

            out.append("\n## Enabled by default\n\n");
            for (MetricId id : MetricId.values()) {
                if (id.enabledByDefault()) {
                    out.append("- `metrics.").append(id.key()).append("`\n");
                }
            }
            out.append("\n## Disabled by default\n\n");
            for (MetricId id : MetricId.values()) {
                if (!id.enabledByDefault()) {
                    out.append("- `metrics.").append(id.key()).append('`')
                            .append(id.highCardinality()
                                    ? " — **high cardinality**: " + id.cardinalityNote() + "\n"
                                    : "\n");
                }
            }
            return out.toString();
        }
    }

    private static Map<String, String> labelsByFamily(ScrapedMetrics scrape) {
        Map<String, Set<String>> collected = new LinkedHashMap<>();
        for (ScrapedMetrics.Sample sample : scrape.samples()) {
            String family = familyOf(sample.name(), scrape.familyNames());
            Set<String> labels = collected.computeIfAbsent(family, key -> new TreeSet<>());
            sample.labels().keySet().stream()
                    .filter(label -> !label.equals("le") && !label.equals("quantile"))
                    .forEach(labels::add);
        }
        Map<String, String> rendered = new LinkedHashMap<>();
        collected.forEach((family, labels) -> rendered.put(family,
                labels.stream().map(label -> "`" + label + "`")
                        .reduce((a, b) -> a + ", " + b).orElse("")));
        return rendered;
    }

    /** Maps a sample name back to its family, accounting for histogram suffixes. */
    private static String familyOf(String sampleName, Set<String> families) {
        if (families.contains(sampleName)) {
            return sampleName;
        }
        for (String suffix : new String[]{"_bucket", "_count", "_sum", "_total", "_created"}) {
            if (sampleName.endsWith(suffix)) {
                String candidate = sampleName.substring(0, sampleName.length() - suffix.length());
                if (families.contains(candidate)) {
                    return candidate;
                }
            }
        }
        return sampleName;
    }
}
